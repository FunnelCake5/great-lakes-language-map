// "Data gaps" panel (CLAUDE.md rule 4, SPEC § Data gaps panel): every
// needs_source and contested item by id, so the backlog stays visible.
// Tapping an item jumps to it on the map. Same list as data/GAPS.md.
import type { GapItem, GapSection } from '../data/gaps';

function h<K extends keyof HTMLElementTagNameMap>(tag: K, attrs: Record<string, string> = {}, ...children: (Node | string)[]) {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, v);
  el.append(...children);
  return el;
}

/** Render `code` spans from the GAPS.md wording. */
function richText(text: string): (Node | string)[] {
  return text.split(/(`[^`]+`)/).filter(Boolean).map((part) => (part.startsWith('`') ? h('code', {}, part.slice(1, -1)) : part));
}

const KIND_LABEL: Record<GapItem['kind'], string> = {
  event: 'Event', nation: 'Nation', placename: 'Place', chapter: 'Chapter', maize: 'Maize line',
};

export function gapsContent(sections: GapSection[], manual: string[], go: (item: GapItem) => void): HTMLElement {
  const total = sections.filter((s) => s.id === 'needs' || s.id === 'contested').reduce((n, s) => n + s.items.length, 0);
  const intro = h('p', { class: 'key-note' },
    `${total} items need a source or are contested. They are drawn dashed or ghosted on the map and never shown as settled. Tap one to go to it.`);

  const blocks = sections.map((s) => {
    const rows = s.items.map((it) => {
      const actionable = it.kind !== 'chapter';
      const row = h('button', {
        type: 'button',
        class: `gap-row kind-${it.kind}${actionable ? '' : ' static'}`,
        ...(actionable ? {} : { 'aria-disabled': 'true' }),
      }, h('span', { class: 'gap-kind' }, KIND_LABEL[it.kind]), h('span', { class: 'gap-text' }, ...richText(it.text.replace(/^(event|nation|placename|chapter) /, ''))));
      if (actionable) row.addEventListener('click', () => go(it));
      return row;
    });
    const open = s.id === 'needs' || s.id === 'contested';
    const details = h('details', { class: `gap-section sec-${s.id}` },
      h('summary', {}, h('span', {}, s.title), h('span', { class: 'gap-count' }, String(s.items.length))),
      ...(rows.length ? rows : [h('p', { class: 'key-note' }, 'None.')]));
    if (open) details.setAttribute('open', '');
    return details;
  });

  const manualBlock = h('details', { class: 'gap-section sec-manual' },
    h('summary', {}, h('span', {}, 'Other known gaps'), h('span', { class: 'gap-count' }, String(manual.length))),
    h('ul', { class: 'gap-manual' }, ...manual.map((m) => h('li', {}, ...richText(m)))));

  return h('div', { class: 'gaps-panel' }, intro, ...blocks, manualBlock,
    h('p', { class: 'key-note' }, 'The same list lives in data/GAPS.md, regenerated by npm run gaps.'));
}

export function gapCount(sections: GapSection[]) {
  return sections.filter((s) => s.id === 'needs' || s.id === 'contested').reduce((n, s) => n + s.items.length, 0);
}
